with open("G:/TBuild/tdesktop/Telegram/SourceFiles/ui/all_keys.txt", "r", encoding="utf-8") as f:
    all_raw = [line.strip().split("\t") for line in f if line.strip()]

all_keys = [x[0] for x in all_raw]
comments = {x[0]: (x[2] if len(x) > 2 else "") for x in all_raw}
raw_palette = {x[0]: x[1] for x in all_raw}

def resolve_palette_alpha(k, visited=None):
    if visited is None: visited = set()
    if k in visited: return 255
    visited.add(k)
    v = raw_palette.get(k, "")
    if "|" in v: v = v.split("|")[0].strip()
    if v.startswith("#"):
        h = v[1:]
        if len(h) == 8: return int(h[6:8], 16)
        elif len(h) == 4: return int(h[3]*2, 16)
        else: return 255
    elif v in raw_palette:
        return resolve_palette_alpha(v, visited)
    return 255

palette_alphas = {k: resolve_palette_alpha(k) for k in all_keys}

EXPLICIT_MAP = {}

def add(key, role, desc, alpha=None):
    if key not in raw_palette:
        print(f"Warning: {key} not found in palette keys!")
    a = alpha if alpha is not None else palette_alphas.get(key, 255)
    EXPLICIT_MAP[key] = (role, a, desc)

